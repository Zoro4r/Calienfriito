from pydantic import BaseModel, Field
from datetime import datetime
from typing import Optional


class SensorReading(BaseModel):
    sensor_id: str
    # None when the node's DHT22 gave no reading: the rest of the reading is still stored
    # so the dashboard shows what the node does measure and flags the DHT22.
    temperature: Optional[float] = Field(None, description="Temperature in Celsius")
    humidity: Optional[float] = Field(None, description="Relative humidity percentage")
    co2_ppm: Optional[float] = Field(None, description="CO2 concentration in ppm")
    co_ppm: float = Field(0.0, description="Carbon monoxide concentration in ppm (MQ7 sensor)")
    camera_occupancy: Optional[int] = Field(
        None,
        description=(
            "Current headcount measured by the sensor node's camera (MediaPipe "
            "line-crossing count). Persisted alongside the CO2-derived "
            "actual_occupancy to validate/calibrate the mass-balance proxy. "
            "Not a model feature; None when the node has no camera."
        ),
    )
    is_simulated: bool = Field(False, description="True when generated by the dev tool, not real hardware")
    node_state: Optional[dict] = Field(
        None,
        description=(
            "Decision taken ON THE NODE (ESP32 heuristic + local CO alarm) when the "
            "reading arrives over MQTT: action, reason, actuators, hysteresis lock. "
            "Stored next to the backend's cognitive_action so both logics can be "
            "compared. None for readings posted over HTTP."
        ),
    )
    timestamp: datetime = Field(default_factory=datetime.utcnow)
